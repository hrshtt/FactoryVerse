@dataclass
class CraftingFinishedEvent(GameEvent):
    """Crafting completed (for fire-and-forget NQ/DQ pattern).

    This event is sent when crafting queued via the non-blocking pattern
    completes. It allows agents to craft items while doing other work
    and be notified when items are ready.

    Note: This is different from action completion for awaited crafts.
    """

    @property
    def recipe(self) -> str:
        """Recipe that was crafted."""
        return self.data.get("recipe", "unknown")

    @property
    def count(self) -> int:
        """Number of items crafted."""
        return self.data.get("count", 0)

    @property
    def action_id(self) -> Optional[str]:
        """Original action_id if linked."""
        return self.data.get("action_id")

    def __str__(self) -> str:
        return f"Crafting Complete: {self.recipe} x{self.count}"


