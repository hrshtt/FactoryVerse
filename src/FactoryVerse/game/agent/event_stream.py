"""EventStream - Temporal perception of game events.

Provides the agent's view of asynchronous game state changes.
This is the temporal complement to spatial views (ReachableView, RemoteView).

Agent Perception Model:
    Spatial (where things are):
        - ReachableView: nearby entities, mutable
        - RemoteView: map-wide via DuckDB, read-only

    Temporal (what's happening):
        - EventStream: game events over time

Events are generated by the Lua mod and sent via UDP. They include:
    - Research completions (unlocks new capabilities)
    - Crafting completions (for fire-and-forget NQ/DQ pattern)
    - Entity lifecycle events (future)
"""

from __future__ import annotations

import asyncio
import logging
import queue
from dataclasses import dataclass, field
from datetime import datetime
from typing import (
    Any,
    Awaitable,
    Callable,
    Dict,
    List,
    Optional,
    TYPE_CHECKING,
    TypeVar,
    Union,
)

if TYPE_CHECKING:
    from FactoryVerse.game.agent.infra.async_listener import AsyncActionListener

logger = logging.getLogger(__name__)

# Type for unsubscribe function
Unsubscribe = Callable[[], None]

# Event callback type
EventCallback = Callable[["GameEvent"], Awaitable[None]]

# Type variable for typed events
E = TypeVar("E", bound="GameEvent")


# =============================================================================
# Event Types
# =============================================================================


@dataclass
class GameEvent:
    """Base event from game.

    All game notifications are wrapped in this type for consistent handling.
    Subclasses provide typed access to event-specific data.

    Attributes:
        notification_type: Event type (e.g., "research_finished", "crafting_finished")
        agent_id: Numeric agent ID that received this event
        tick: Game tick when event occurred
        data: Event-specific payload
        timestamp: When Python received the event
    """
    notification_type: str
    agent_id: int
    tick: int
    data: Dict[str, Any]
    timestamp: datetime = field(default_factory=datetime.now)
    # Stream provenance (NOTIFICATIONS plan). None for events that did not
    # arrive on a sequenced stream.
    epoch: Optional[int] = None
    seq: Optional[int] = None
    source: Optional[str] = None
    filled_from_file: bool = False

    @property
    def is_critical(self) -> bool:
        """Whether this event significantly changes agent capabilities.

        Critical events may warrant immediate attention in the agent loop.
        """
        return self.notification_type in {
            "research_finished",   # New recipes/capabilities unlocked
            "crafting_finished",   # Items now available in inventory
        }

    def to_dict(self) -> Dict[str, Any]:
        """Return the stable wire representation used by coding harnesses."""
        out = {
            "notification_type": self.notification_type,
            "agent_id": self.agent_id,
            "tick": self.tick,
            "data": self.data,
            "critical": self.is_critical,
        }
        if self.seq is not None:
            out["epoch"] = self.epoch
            out["seq"] = self.seq
            out["source"] = self.source
            if self.filled_from_file:
                out["filled_from_file"] = True
        return out

    @classmethod
    def from_payload(cls, payload: Dict[str, Any]) -> "GameEvent":
        """Create appropriate event type from UDP payload.

        Dispatches to typed subclasses based on notification_type.
        """
        notification_type = payload.get("notification_type", "unknown")
        common = dict(
            notification_type=notification_type,
            agent_id=payload.get("agent_id", 0),
            tick=payload.get("tick", 0),
            data=payload.get("data", {}),
            epoch=payload.get("epoch"),
            seq=payload.get("seq"),
            source=payload.get("source"),
            filled_from_file=bool(payload.get("filled_from_file", False)),
        )

        # Dispatch to typed subclass — one branch per wire.turn name.
        if notification_type == "research_finished":
            return ResearchFinishedEvent(**common)
        elif notification_type == "research_started":
            return ResearchStartedEvent(**common)
        elif notification_type == "research_cancelled":
            return ResearchCancelledEvent(**common)
        elif notification_type == "research_queued":
            return ResearchQueuedEvent(**common)
        elif notification_type == "research_moved":
            return ResearchMovedEvent(**common)
        elif notification_type == "research_reversed":
            return ResearchReversedEvent(**common)
        elif notification_type == "crafting_finished":
            return CraftingFinishedEvent(**common)
        else:
            # Generic event for unknown types
            return cls(**common)


