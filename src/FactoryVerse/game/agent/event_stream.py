@dataclass
class ResearchFinishedEvent(GameEvent):
    """Research technology completed.

    This is a critical event - new recipes and capabilities are unlocked.
    The agent should re-evaluate its strategy when this occurs.
    """

    @property
    def technology(self) -> str:
        """Name of completed technology."""
        return self.data.get("technology", "unknown")

    @property
    def unlocked_recipes(self) -> List[str]:
        """Recipes unlocked by this technology."""
        return self.data.get("unlocked_recipes", [])

    @property
    def effects(self) -> List[Dict[str, Any]]:
        """Normalized technology effects applied at completion."""
        return self.data.get("effects", [])

    @property
    def level(self) -> Optional[int]:
        """Technology level (for infinite research)."""
        return self.data.get("level")

    def __str__(self) -> str:
        recipes = ", ".join(self.unlocked_recipes) if self.unlocked_recipes else "none"
        return f"Research Complete: {self.technology} (unlocked: {recipes})"


@dataclass
class ResearchStartedEvent(GameEvent):
    """Research technology started."""

    @property
    def technology(self) -> str:
        """Name of technology being researched."""
        return self.data.get("technology", "unknown")

    def __str__(self) -> str:
        return f"Research Started: {self.technology}"


@dataclass
class ResearchCancelledEvent(GameEvent):
    """Research cancelled."""

    @property
    def technologies(self) -> Dict[str, Any]:
        """Technologies that were cancelled."""
        return self.data.get("technologies", {})

    def __str__(self) -> str:
        techs = ", ".join(self.technologies.keys()) if self.technologies else "unknown"
        return f"Research Cancelled: {techs}"


@dataclass
class ResearchQueuedEvent(GameEvent):
    """Research added to queue."""

    @property
    def technology(self) -> str:
        """Name of queued technology."""
        return self.data.get("technology", "unknown")

    def __str__(self) -> str:
        return f"Research Queued: {self.technology}"


@dataclass
class ResearchMovedEvent(GameEvent):
    """Research queue reordered (force-scoped)."""

    def __str__(self) -> str:
        return "Research Queue Reordered"


@dataclass
class ResearchReversedEvent(GameEvent):
    """Research un-researched (force-scoped)."""

    @property
    def technology(self) -> str:
        return self.data.get("technology", "unknown")

    def __str__(self) -> str:
        return f"Research Reversed: {self.technology}"


